    test('then the correct workspace root directory is found', () async {
      expect(
        projectFilePreparer.rootDirectory.path,
        equals(p.join(d.sandbox, 'monorepo')),
      );
    });

    test('then the preparer is marked as a workspace', () async {
      expect(projectFilePreparer.isWorkspace, isTrue);
    });

    test('then the correct included package paths are returned', () async {
      expect(
        projectFilePreparer.includedPackagePaths,
        containsAll(['packages/dart_utilities', 'project/project_server']),
      );
    });

    test('then the included subpaths include packages and .scloud', () async {
      expect(
        projectFilePreparer.includedSubPaths,
        containsAll([
          'packages/dart_utilities',
          'project/project_server',
          '.scloud',
        ]),
      );
    });

    test('then .scloud/scloud_server_dir file is created.', () async {
      final descriptor = d.dir('.scloud', [
        d.file('scloud_server_dir', 'project/project_server'),
      ]);

      await expectLater(
        descriptor.validate(p.join(d.sandbox, 'monorepo')),
        completes,
      );
    });

    test('then .scloud/scloud_ws_pubspec.yaml is not created', () async {
      final scloudRootPubspec = File(
        p.join(d.sandbox, 'monorepo', '.scloud', 'scloud_ws_pubspec.yaml'),
      );
      expect(scloudRootPubspec.existsSync(), isFalse);
    });

    test('then filterPubspecLock retains packages reachable '
        'from the server package', () async {
      expect(
        filteredPubspecLock,
        stringContainsInOrder(['# Generated by scloud', 'packages:']),
      );

      final packages =
          (yamlDecode(filteredPubspecLock) as Map)['packages'] as Map;

      expect(
        packages.keys,
        containsAll([
          'project_server',
          'dart_utilities',
          'serverpod',
          'collection',
        ]),
      );
    });

    test('then filterPubspecLock omits packages unreachable '
        'from the server package', () async {
      final packages =
          (yamlDecode(filteredPubspecLock) as Map)['packages'] as Map;

      expect(packages.containsKey('flutter'), isFalse);
      expect(packages.containsKey('flutter_utilities'), isFalse);
      expect(packages.containsKey('project_app'), isFalse);
      expect(packages.containsKey('project_client'), isFalse);
    });

    test('then filterPubspecLock demotes packages that are no '
        'longer direct root dependencies to transitive', () async {
      final packages =
          (yamlDecode(filteredPubspecLock) as Map)['packages'] as Map;

      expect(packages['collection'], containsPair('dependency', 'transitive'));
      expect(
        packages['dart_utilities'],
        containsPair('dependency', 'direct main'),
      );
      expect(packages['serverpod'], containsPair('dependency', 'direct main'));
    });
  });

