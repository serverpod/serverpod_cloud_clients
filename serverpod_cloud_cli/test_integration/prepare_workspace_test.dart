        expect(
          () => task(d.sandbox),
          throwsA(
            isA<WorkspaceException>().having(
              (final e) => e.errors,
              'errors',
              equals([
                'A Flutter dependency is not allowed in a server package: flutter_utilities',
              ]),
            ),
          ),
        );
      });
    },
  );

